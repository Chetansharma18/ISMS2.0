/** Expands the remark shorthand used in the compact rows above. */
function expandRemark(code: string): string {
  switch (code) {
    case 'E': return 'Expired';
    case 'NV': return 'Not Valid';
    case 'V': return 'New Version';
    case 'C': return 'New Course';
  }
  const modified = /^M(\d+)$/.exec(code);
  return modified ? `Modify version – course hours changed (previously ${modified[1]})` : code;
}

/** Builds the full, numbered Course Master seed list (Sr.No. 1 to 568). */
export function buildCourseCatalogue(): CourseMasterItem[] {
  const items: CourseMasterItem[] = [];
  let lastCode = '';
  let lastName = '';

  for (const [sector, rows] of CATALOGUE) {
    for (const [code, name, version, nsqf, norms, theory, practical, total, validUpTo, remark] of rows) {
      const jobRoleCode = code || lastCode;
      const jobRoleName = name || lastName;
      lastCode = jobRoleCode;
      lastName = jobRoleName;

      const sNo = items.length + 1;
      items.push({
        sNo,
        id: `c-${sNo}`,
        sector,
        jobRoleName,
        jobRoleCode,
        version,
        nsqfLevel: nsqf,
        commonNormsCategory: norms,
        theoryDurationHours: theory,
        practicalOjtDurationHours: practical,
        itSoftSkillTrainingHours: IT_SOFT_SKILL_HOURS,
        totalQpHours: total,
        courseValidUpToDate: validUpTo || '-',
        remark: expandRemark(remark)
      });
    }
  }

  return items;
}
