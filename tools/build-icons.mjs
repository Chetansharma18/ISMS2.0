#!/usr/bin/env node
/**
 * The outline icons of the portal come from Lucide (https://lucide.dev, ISC license), so every icon has the same
 * drawing style. The app keeps its own short names (<app-icon name="close" />); this tool connects them.
 *
 *   tools/icons.map.json                  our name -> Lucide name   (the only file you edit)
 *   src/app/shared/components/icon/icons.lucide.ts   GENERATED from it, with the path data of lucide-static
 *
 *   npm run icons:build                   regenerate icons.lucide.ts after editing the map
 *   npm run icons:find -- <word>          search the 1,900 Lucide icons by name or tag, e.g. "calendar"
 *   node tools/build-icons.mjs --check    fail when icons.lucide.ts is not what the map produces (run by npm run verify)
 *
 * To add an icon: find it (icons:find), add  "my-name": "lucide-name"  to icons.map.json (keep it sorted), run icons:build.
 * Never paste SVG path data into a component or into icons.lucide.ts.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const mapPath = join(root, 'tools', 'icons.map.json');
const outPath = join(root, 'src', 'app', 'shared', 'components', 'icon', 'icons.lucide.ts');
const lucideDir = join(root, 'node_modules', 'lucide-static');

if (!existsSync(lucideDir)) {
  console.error('build-icons: lucide-static is not installed. Run "npm install".');
  process.exit(1);
}

const nodes = JSON.parse(readFileSync(join(lucideDir, 'icon-nodes.json'), 'utf8'));
const lucideVersion = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8')).version;

// ---- search ------------------------------------------------------------------------------------------------------
if (process.argv[2] === '--find') {
  const word = (process.argv[3] ?? '').toLowerCase();
  if (!word) {
    console.error('usage: npm run icons:find -- <word>');
    process.exit(1);
  }
  const tags = existsSync(join(lucideDir, 'tags.json')) ? JSON.parse(readFileSync(join(lucideDir, 'tags.json'), 'utf8')) : {};
  const hits = Object.keys(nodes).filter(name => name.includes(word) || (tags[name] ?? []).some(tag => tag.includes(word)));
  console.log(hits.length ? hits.join('\n') : 'no Lucide icon matches "' + word + '"');
  process.exit(0);
}

// ---- SVG element -> path data ------------------------------------------------------------------------------------
const n = value => String(Math.round(Number(value) * 1000) / 1000);

function toPath([tag, a]) {
  switch (tag) {
    case 'path':
      return a.d;
    case 'circle': {
      const { cx, cy, r } = a;
      return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0`;
    }
    case 'ellipse': {
      const { cx, cy, rx, ry } = a;
      return `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0`;
    }
    case 'line':
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${n(pts[0])} ${n(pts[1])}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${n(pts[i])} ${n(pts[i + 1])}`;
      return tag === 'polygon' ? d + 'Z' : d;
    }
    case 'rect': {
      const x = Number(a.x ?? 0);
      const y = Number(a.y ?? 0);
      const w = Number(a.width);
      const h = Number(a.height);
      const r = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}Z`;
      return `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(r)}v${n(h - 2 * r)}a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(r)}h${n(-(w - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(-r)}v${n(-(h - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(-r)}Z`;
    }
    default:
      throw new Error('unsupported SVG element <' + tag + '>');
  }
}

// ---- build -------------------------------------------------------------------------------------------------------
const map = JSON.parse(readFileSync(mapPath, 'utf8'));
const names = Object.keys(map).sort();
const problems = [];
const lines = [];

for (const name of names) {
  const lucide = map[name];
  const node = nodes[lucide];
  if (!node) {
    problems.push(`"${name}": Lucide has no icon "${lucide}" (try: npm run icons:find -- ${lucide.split('-')[0]})`);
    continue;
  }
  const key = /^[a-z][a-z0-9]*$/.test(name) ? name : `'${name}'`;
  const paths = node.map(element => `'${toPath(element)}'`);
  lines.push(`  ${key}: [\n    ${paths.join(',\n    ')}\n  ]`);
}

if (problems.length > 0) {
  console.error('build-icons: fix icons.map.json\n  ' + problems.join('\n  '));
  process.exit(1);
}

const output = `// GENERATED by tools/build-icons.mjs from Lucide (lucide-static ${lucideVersion}, ISC license, https://lucide.dev).
// Do not edit. Change tools/icons.map.json and run: npm run icons:build
//
// Every icon is SVG path data on a 24x24 grid, drawn with a stroke (round caps and joins).

export const LUCIDE_ICONS = {
${lines.join(',\n')}
} as const satisfies Record<string, readonly string[]>;
`;

if (process.argv[2] === '--check') {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== output) {
    console.error('build-icons: icons.lucide.ts is out of date with tools/icons.map.json. Run: npm run icons:build');
    process.exit(1);
  }
  console.log('build-icons: ok (' + names.length + ' icons)');
} else {
  writeFileSync(outPath, output);
  console.log('build-icons: wrote ' + names.length + ' icons to src/app/shared/components/icon/icons.lucide.ts');
}
